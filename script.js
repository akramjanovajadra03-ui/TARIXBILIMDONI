function showQuestion() {
  clearInterval(timer);
  locked = false;
  time = 20;

  const q = questions[index];

  document.getElementById("questionNumber").textContent =
    `${index + 1} / 10`;

  document.getElementById("timer").textContent = time;
  document.getElementById("questionText").textContent = q[0];
  document.getElementById("progressBar").style.width =
    `${index * 10}%`;

  document.getElementById("feedback").textContent = "";
  const box = document.getElementById("answers");
  box.innerHTML = "";

  q[1].forEach((option, i) => {
    const btn = document.createElement("button");
    btn.className = "answer-btn";
    btn.textContent = `${String.fromCharCode(65 + i)}. ${option}`;
    btn.addEventListener("click", () => chooseAnswer(i));
    box.appendChild(btn);
  });

  timer = setInterval(() => {
    time--;
    document.getElementById("timer").textContent = time;

    if (time <= 0) {
      clearInterval(timer);
      chooseAnswer(null);
    }
  }, 1000);
}

function chooseAnswer(choice) {
  if (locked) return;

  locked = true;
  clearInterval(timer);

  const q = questions[index];
  const rightIndex = q[2];
  const isRight = choice === rightIndex;

  if (isRight) correct++;
  else wrong++;

  answersHistory.push({
    question: q[0],
    selected: choice === null ? "Javob berilmadi" : q[1][choice],
    correct: q[1][rightIndex],
    isRight
  });

  document.querySelectorAll(".answer-btn").forEach((btn, i) => {
    btn.disabled = true;
    if (i === rightIndex) btn.classList.add("correct");
    if (i === choice && !isRight) btn.classList.add("wrong");
  });

  const feedback = document.getElementById("feedback");
  feedback.textContent = isRight ? "✓ To‘g‘ri javob!" :
    choice === null ? "Vaqt tugadi!" : "✗ Noto‘g‘ri javob!";
  feedback.style.color = isRight ? "#20d878" : "#ff6666";

  setTimeout(() => {
    index++;
    if (index < 10) showQuestion();
    else showResult();
  }, 1000);
}

function showResult() {
  clearInterval(timer);
  quizScreen.classList.add("hidden");
  resultScreen.classList.remove("hidden");

  document.getElementById("studentResult").textContent =
    `O‘quvchi: ${name}`;

  document.getElementById("score").textContent = correct * 10;
  document.getElementById("correctCount").textContent = correct;
  document.getElementById("wrongCount").textContent = wrong;
  document.getElementById("levelResult").textContent =
    `Tanlangan milliy sertifikat darajasi: ${level}`;

  const review = document.getElementById("answerReview");
  review.innerHTML = "";

  answersHistory.forEach((item, i) => {
    const card = document.createElement("div");
    card.className = `review-item ${item.isRight ? "right" : "wrong"}`;

    const q = document.createElement("p");
    q.className = "review-question";
    q.textContent = `${i + 1}. ${item.question}`;

    const your = document.createElement("p");
    your.className = "your-answer";
    your.textContent = `Sizning javobingiz: ${item.selected}`;
    if (item.isRight) your.classList.add("good");

    const right = document.createElement("p");
    right.className = "correct-answer";
    right.textContent = `To‘g‘ri javob: ${item.correct}`;

    card.append(q, your, right);
    review.appendChild(card);
  });

  document.getElementById("progressBar").style.width = "100%";
}
